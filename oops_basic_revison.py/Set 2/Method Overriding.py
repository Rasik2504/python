# QUESTION 5: ANIMAL SOUND SYSTEM
#
# Create a parent class called Animal.
#
# Requirements:
# 1. Create a method called sound().
#
# 2. The method should print:
#       "Animal makes a sound"
#
#
# Create a child class called Dog.
#
# 3. Dog should inherit from Animal.
#
# 4. Override the sound() method.
#
# 5. Dog's sound() should print:
#       "Dog barks"
#
#
# Create another child class called Cat.
#
# 6. Cat should inherit from Animal.
#
# 7. Override the sound() method.
#
# 8. Cat's sound() should print:
#       "Cat meows"
#
#
# Main program:
# 9. Create objects of Animal, Dog, and Cat.
#
# 10. Call sound() for each object.
#
# 11. Create a list containing Dog and Cat objects.
#
# 12. Use one for loop to call sound()
#     for every object in the list.
#
# Concepts to practice:
# - Inheritance
# - Method overriding
# - Polymorphism
# - Parent class
# - Child class
# - for loop with objects